function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}


function renderContacts(contacts = [], contactGroups = []) {

  // Contactos agrupados
  if (contactGroups.length) {

    return `
      <div class="info-block">
        <h3>Cómo contactarse</h3>

        <div class="contact-groups">

          ${contactGroups.map(group => `

            <div class="contact-group">

              <h4>
                ${escapeHtml(group.title)}
              </h4>

              <div class="contacts">

                ${group.contacts.map(contact => `

                  <a
                    class="contact-link"
                    href="${escapeHtml(contact.href)}"
                    ${contact.href.startsWith("http")
                      ? 'target="_blank" rel="noopener noreferrer"'
                      : ""}
                  >
                    ${escapeHtml(contact.label)}:
                    ${escapeHtml(contact.text)}
                  </a>

                `).join("")}

              </div>

            </div>

          `).join("")}

        </div>
      </div>
    `;
  }


  // Contactos normales
  if (!contacts.length) return "";


  return `
    <div class="info-block">

      <h3>Cómo contactarse</h3>

      <div class="contacts">

        ${contacts.map(contact => `

          <a
            class="contact-link"
            href="${escapeHtml(contact.href)}"
            ${contact.href.startsWith("http")
              ? 'target="_blank" rel="noopener noreferrer"'
              : ""}
          >
            ${escapeHtml(contact.text)}
          </a>

        `).join("")}

      </div>

    </div>
  `;
}


function renderResources(resources = []) {
  if (!resources.length) return "";

  return `
    <div class="info-block">
      <h3>Recursos</h3>

      <div class="resource-list">
        ${resources.map(resource => `
          <a
            class="resource-link"
            href="${escapeHtml(resource.href)}"
            target="_blank"
            rel="noopener noreferrer"
          >
            ${escapeHtml(resource.label)}
          </a>
        `).join("")}
      </div>
    </div>
  `;
}


function renderCard(item) {

  const useList = item.use
    .map(text => `<li>${escapeHtml(text)}</li>`)
    .join("");

  return `
    <article
      class="card"
      id="${escapeHtml(item.id)}"
      data-search="${escapeHtml([
        item.title,
        item.subtitle,
        item.what,
        ...item.use,
        ...(item.contacts || []).map(contact => contact.text),
        item.note || ""
      ].join(" "))}"
    >

      <header class="card-head">

        <div class="card-number">
          ${escapeHtml(item.number)}
        </div>

        <div>
          <h2 class="card-title">
            ${escapeHtml(item.title)}
          </h2>

          <p class="card-subtitle">
            ${escapeHtml(item.subtitle)}
          </p>
        </div>

      </header>


      <div class="card-body">

        <div class="info-block">
          <h3>Qué es</h3>

          <p>
            ${escapeHtml(item.what)}
          </p>
        </div>


        <div class="info-block">
          <h3>Para qué se usa</h3>

          <ul>
            ${useList}
          </ul>
        </div>


        ${
          item.security
            ? `
              <div class="security-alert">
                <strong>Ante una situación de seguridad</strong>

                <span>
                  La comunicación debe realizarse de manera inmediata
                  por el canal habilitado y, cuando corresponda,
                  mediante CIDI.
                </span>
              </div>
            `
            : ""
        }


        ${renderContacts(item.contacts, item.contactGroups)}


        ${renderResources(item.resources)}


        ${
          item.note
            ? `
              <div class="card-note">
                ${escapeHtml(item.note)}
              </div>
            `
            : ""
        }


        ${
          item.sourceNote
            ? `
              <div class="card-note">
                ${escapeHtml(item.sourceNote)}
              </div>
            `
            : ""
        }

      </div>

    </article>
  `;
}


function renderAll(list = resources) {

  cardsEl.innerHTML = list
    .map(renderCard)
    .join("");


  tocEl.innerHTML = list
    .map(item => `
      <a
        href="#${escapeHtml(item.id)}"
        data-target="${escapeHtml(item.id)}"
      >
        ${escapeHtml(item.number)} · ${escapeHtml(item.title)}
      </a>
    `)
    .join("");


  emptyEl.hidden = list.length !== 0;


  resultCountEl.textContent =
    `${list.length} ${list.length === 1 ? "recurso" : "recursos"}`;
}


function renderContactsIndex() {

  const allContacts = resources.flatMap(resource =>
    (resource.contacts || []).map(contact => ({
      area: resource.title,
      ...contact
    }))
  );


  contactListEl.innerHTML = allContacts
    .map(contact => `
      <div class="contact-item">

        <h3>
          ${escapeHtml(contact.area)}
        </h3>

        <p>
          ${escapeHtml(contact.label)}
        </p>

        <a
          href="${escapeHtml(contact.href)}"
          ${contact.href.startsWith("http")
            ? 'target="_blank" rel="noopener noreferrer"'
            : ""}
        >
          ${escapeHtml(contact.text)}
        </a>

      </div>
    `)
    .join("");
}


function normalize(text) {

  return text
    .toLocaleLowerCase("es")
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "");
}


function filterResources(query) {

  const normalizedQuery =
    normalize(query.trim());


  if (!normalizedQuery) {

    renderAll(resources);

    updateActiveToc();

    return;
  }


  const filtered =
    resources.filter(resource => {

      const haystack =
        normalize([
          resource.title,
          resource.subtitle,
          resource.what,

          ...resource.use,

          ...(resource.contacts || [])
            .map(contact =>
              `${contact.label} ${contact.text}`
            ),

          ...(resource.resources || [])
            .map(resource =>
              resource.label
            ),

          resource.note || ""

        ].join(" "));


      return haystack.includes(normalizedQuery);
    });


  renderAll(filtered);

  updateActiveToc();
}


searchEl.addEventListener("input", event => {

  filterResources(event.target.value);

});


function updateActiveToc() {

  const links =
    [...tocEl.querySelectorAll("a")];

  const cards =
    resources
      .map(resource =>
        document.getElementById(resource.id)
      )
      .filter(Boolean);


  let current =
    cards[0]?.id;


  for (const card of cards) {

    if (
      window.scrollY + 150 >=
      card.offsetTop
    ) {
      current = card.id;
    }
  }


  links.forEach(link => {

    link.classList.toggle(
      "active",
      link.dataset.target === current
    );

  });
}


window.addEventListener(
  "scroll",
  updateActiveToc,
  { passive: true }
);


renderAll();

renderContactsIndex();

updateActiveToc();


